// Generates campaign/maps/*.yaml from the shapes below, so the asteroid walls are exact.
// Run: node campaign/tools/gen_maps.mjs   (rewrites the five map files)
// The output is the normal engine map format; terrain uses only the shapes engine/rules.js
// understands (a single hex, `size: 3` = an east-west line of 3, `radius: N` = a disc).
// Campaign zones are added under map.zones as lists of [q, r]; buildRules ignores lists.
import fs from 'node:fs';
import path from 'node:path';
import { CAMPAIGN, H, allCells, xOf } from './lib.mjs';

const K = H.key, U = H.unkey;

// Cover a set of cells with as few legal terrain entries as possible (discs, lines, singles),
// never spilling outside the set or the board.
function cover(cellKeys, R) {
  const S = new Set(cellKeys), left = new Set(cellKeys), out = [];
  const fits = (cells) => cells.every((c) => S.has(K(c)) && H.inHexagon(c, R));
  const gain = (cells) => cells.filter((c) => left.has(K(c))).length;
  const take = (cells, entry) => { cells.forEach((c) => left.delete(K(c))); out.push(entry); };
  for (const [rad, min] of [[2, 12], [1, 5]]) {
    for (;;) {
      let best = null;
      for (const k of S) {
        const c = U(k), cells = H.disc(c, rad);
        if (!fits(cells)) continue;
        const g = gain(cells);
        if (g >= min && (!best || g > best.g)) best = { g, c, cells };
      }
      if (!best) break;
      take(best.cells, { at: best.c, radius: rad });
    }
  }
  for (;;) {
    let best = null;
    for (const k of left) {
      const c = U(k), cells = [H.add(c, [-1, 0]), c, H.add(c, [1, 0])];
      if (!fits(cells)) continue;
      const g = gain(cells);
      if (g >= 2 && (!best || g > best.g)) best = { g, c, cells };
    }
    if (!best) break;
    take(best.cells, { at: best.c, size: 3 });
  }
  for (const k of [...left].sort()) take([U(k)], { at: U(k), size: 1 });
  return out;
}

const fmt = (c) => `[${c[0]}, ${c[1]}]`;
function terrainYaml(type, entries) {
  return entries.map((e) => `    - { type: ${type}, at: ${fmt(e.at)}, ` + (e.radius ? `radius: ${e.radius} }` : `size: ${e.size} }`)).join('\n');
}

function writeMap(m) {
  const R = m.radius, all = allCells(R).map(K);
  const ast = new Set(m.asteroid.map(K).filter((k) => all.includes(k)));
  const neb = new Set(m.nebula.map(K).filter((k) => all.includes(k) && !ast.has(k)));
  const zoneLines = Object.entries(m.zones).map(([z, cells]) => {
    const list = cells.filter((c) => H.inHexagon(c, R) && !ast.has(K(c)));
    return `    ${z}: [${list.map(fmt).join(', ')}]`;
  });
  const y = `# ============================================================
#  CAMPAIGN MAP  -  "${m.name}"   (Shatkon: The Weave, ${m.chapter})
${m.notes.map((n) => '#  ' + n).join('\n')}
#  Generated by campaign/tools/gen_maps.mjs - edit the shapes there and re-run.
#  Coordinates are [q, r] hex coordinates; [0, 0] is the centre; r grows to the south.
#  Zones given as lists of [q, r] are campaign zones (script triggers, spawns, AI paths);
#  the engine ignores them outside the campaign.
# ============================================================

map:
  name: "${m.name}"
  world: world_v0.4.yaml

  board:
    shape: hexagon
    radius: ${R}

  zones:
    player_1_home:  { edge: south, depth: ${m.homeSouth} }
    player_2_home:  { edge: north, depth: ${m.homeNorth} }
    no_mans_land:   { everything_else: true }
${zoneLines.join('\n')}

  setup:
    secret: true
    ships: own_home_zone
    drones: own_home_zone
    mines: { own_home_zone: true, rows_into_no_mans_land: ${m.mineRows} }

  terrain:
${terrainYaml('asteroid', cover([...ast], R))}${neb.size ? '\n' + terrainYaml('nebula', cover([...neb], R)) : ''}
`;
  fs.writeFileSync(path.join(CAMPAIGN, 'maps', m.id + '.yaml'), y);
  console.log(`${m.id}: ${ast.size} asteroid hexes, ${neb.size} nebula hexes`);
}

const where = (R, f) => allCells(R).filter(f);
const ring = (c, r) => H.disc(c, r).filter((x) => H.dist(x, c) === r);

// ---------------- ch1_corridor ----------------
// A straight north-south corridor 3-4 hexes wide (|x| <= 1.5, x = q + r/2), walled by
// asteroids. The two end rows of each home zone open a little (|x| <= 2.5) so ships can
// deploy side by side.
{
  const R = 7;
  const open = (c) => Math.abs(xOf(c)) <= 1.5 || (Math.abs(c[1]) >= 6 && Math.abs(xOf(c)) <= 2.5);
  writeMap({
    id: 'ch1_corridor', name: 'The Corridor', chapter: 'chapter 1', radius: R, homeSouth: 5, homeNorth: 3, mineRows: 0,
    notes: ['A narrow asteroid corridor, 3-4 hexes wide, running the length of the board.',
      'Humans deploy in the south (rows 3-7), the Seed in the north (rows -7 to -5).',
      'Asteroids block movement and lasers, not sensors: you can see through the walls but not shoot.'],
    asteroid: where(R, (c) => !open(c)), nebula: [],
    zones: { corridor_mid: where(R, (c) => open(c) && Math.abs(c[1]) <= 1) },
  });
}

// ---------------- ch2_quiet_water ----------------
// A two-row asteroid wall across the middle (rows 0 and 1). The only gap a 2-hex ship fits
// through is in the centre: 3 hexes on row 0, 2 hexes on row 1. A 1-hex slot hugs the
// west edge: only Sparrow fits. A nebula bank sits on the north mouth of the gap.
{
  const R = 8;
  const gap = new Set(['-1,0', '0,0', '1,0', '-1,1', '0,1', '-8,0', '-8,1']);
  const wall = where(R, (c) => (c[1] === 0 || c[1] === 1) && !gap.has(K(c)));
  const scatter = [[4, 3], [-4, 4], [3, -4], [-5, -2], [6, -5], [-2, 7]];
  const nebula = H.disc([0, -2], 1).concat([[2, -3], [-1, -3], [2, -4]]);
  writeMap({
    id: 'ch2_quiet_water', name: 'Quiet Water', chapter: 'chapter 2', radius: R, homeSouth: 4, homeNorth: 3, mineRows: 6,
    notes: ['An asteroid wall across rows 0-1 with one gap in the middle: the only way south for a 2-hex ship.',
      'A nebula bank (-2 signature, -3 sensor) covers the gap\'s north mouth. Mines go in zone minefield.',
      'The west-edge slot ([-8,0], [-8,1]) is 1 hex wide: Sparrow can use it, nothing bigger.'],
    asteroid: wall.concat(scatter), nebula,
    zones: {
      choke: [...H.disc([0, -2], 1), [2, -3], [-1, -3], [-1, 0], [0, 0], [1, 0], [-1, 1], [0, 1], [-1, 2], [0, 2], [1, 2]],
      minefield: [[0, -1], [-1, 0], [1, 0], [0, 1]],
      west_slot: [[-8, 0], [-8, 1]],
    },
  });
}

// ---------------- ch3_splitting ----------------
// A thick asteroid cluster sits right in front of the human start (laser shadow and missile
// trap). Li's wing arrives at the north-east edge, behind the Twin's start.
{
  const R = 9;
  const cluster = [...H.disc([-2, 5], 1), ...H.disc([-1, 3], 1), [-3, 4], [0, 4], [-4, 6]];
  const scatter = [[-6, 2], [-5, 1], [4, -2], [5, -3], [-3, -3], [2, 0], [0, -2], [6, -6], [-6, -1], [3, 3], [-7, 5], [1, -5]];
  writeMap({
    id: 'ch3_splitting', name: 'Meridian Approach', chapter: 'chapter 3', radius: R, homeSouth: 3, homeNorth: 4, mineRows: 0,
    notes: ['A thick asteroid cluster directly north of the human start: cover and a laser shadow.',
      'Zone li_arrival is the north-east edge, behind the Twin\'s start, where li_wing spawns.'],
    asteroid: cluster.concat(scatter), nebula: [],
    zones: {
      li_arrival: where(R, (c) => c[1] <= -8 && c[0] >= 6),
      cover: where(R, (c) => !cluster.some((a) => K(a) === K(c)) && cluster.some((a) => H.dist(a, c) === 1) && c[1] >= 5),
    },
  });
}

// ---------------- ch4a_ashfall ----------------
// Open space; the outpost wreck in the middle is a broken ring of asteroid tiles.
{
  const R = 8;
  const wreck = [[0, 0], [2, -2], [2, -1], [-2, 1], [-2, 2], [-1, -1], [1, 1], [0, -2], [-1, 3], [3, -3]];
  writeMap({
    id: 'ch4a_ashfall', name: 'Ashfall Outpost', chapter: 'chapter 4A', radius: R, homeSouth: 3, homeNorth: 6, mineRows: 0,
    notes: ['Open space; the wrecked outpost (asteroid tiles) sits in the middle.',
      'Zone outpost is every open hex touching the wreck\'s core [0,0]: the dock where the Graft rig lies.',
      'The Weave home zone is deep (rows -8 to -3) so the husks can start near the wreck.'],
    asteroid: wreck, nebula: [[4, -6], [5, -6], [-5, -2], [-6, -1], [-5, -1]],
    zones: { outpost: ring([0, 0], 1) },
  });
}

// ---------------- ch5_bloom ----------------
// A nebula front across the north (rows -6 to -5, |x| <= 7). The Bloom grows out of it.
{
  const R = 10;
  const nebula = where(R, (c) => c[1] >= -7 && c[1] <= -5 && Math.abs(xOf(c)) <= 7.5 && !(c[1] === -5 && Math.abs(xOf(c)) > 5));
  const scatter = [[-6, 0], [5, -1], [2, 2], [-2, -1], [-7, 4], [7, -3], [0, 3], [-3, 3], [8, -6], [-9, -1]];
  writeMap({
    id: 'ch5_bloom', name: 'The Bloom', chapter: 'chapter 5', radius: R, homeSouth: 5, homeNorth: 4, mineRows: 0,
    notes: ['A nebula front across the north (rows -7 to -5). The Bloom spawns in zone bloom_entry inside it.',
      'Humans start close together in the south (rows 6-10).'],
    asteroid: scatter, nebula,
    zones: { bloom_entry: H.disc([4, -8], 1).concat(ring([4, -8], 2).filter((c) => c[1] <= -7)) },
  });
}
